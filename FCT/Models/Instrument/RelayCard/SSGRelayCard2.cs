        private string get_relay_card_DI_value(byte[] byte_, int i)
        {
            string str = BitConverter.ToString(byte_);
            str = str.Replace("-", "");
            str = str.Remove(0, 2);
            str = str.Substring(i * 2 + 1, 1);

            return str;
        }

        private string get_relay_ADC_value(byte[] byte_, int i)
        {
            string test = "";
            int x = 0;
            foreach (byte ii in byte_)
            {
                x++;
                if (i == x)
                {
                    test = ii.ToString();
                    break;
                }
            }
            double b = Convert.ToDouble(test);
            b = b / 100 * 2;
            test = b.ToString("F2");
            return test;
        }

